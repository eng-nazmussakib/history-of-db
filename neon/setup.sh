#!/usr/bin/env bash
# Runs the regular migrations/seeds (../scripts/migrate.sh) against Neon.
#
#   neon/setup.sh                  # create the Neon database if missing + apply migrations
#   neon/setup.sh --seed           # ...and load seeds/
#   neon/setup.sh --reset --seed   # drop and recreate the Neon database first (destroys data)
#   neon/setup.sh --url            # only print the connection string
#
# Needs the Neon CLI, signed in: npm install -g neon@latest && neon login
# Target comes from neon/config.env; NEON_PROJECT_ID / NEON_BRANCH / NEON_DATABASE
# in the environment win (e.g. NEON_BRANCH=dev neon/setup.sh).
# Writes DATABASE_URL (direct, for migrations) to .env.production in history-of-db
# (git-ignored). scripts/migrate.sh never reads that file, so local runs stay local.
set -euo pipefail

NEON_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DB_DIR="$(dirname "$NEON_DIR")"

env_project="${NEON_PROJECT_ID:-}" env_branch="${NEON_BRANCH:-}" env_db="${NEON_DATABASE:-}"
# shellcheck source=config.env
source "$NEON_DIR/config.env"
NEON_PROJECT_ID="${env_project:-$NEON_PROJECT_ID}"
NEON_BRANCH="${env_branch:-$NEON_BRANCH}"
NEON_DATABASE="${env_db:-$NEON_DATABASE}"

command -v neon >/dev/null || { echo "Neon CLI not found: npm install -g neon@latest && neon login" >&2; exit 1; }

URL_ONLY=false
args=()
for arg in "$@"; do
  case "$arg" in
    --url) URL_ONLY=true ;;
    -h|--help) sed -n '2,14p' "$0"; exit 0 ;;
    *) args+=("$arg") ;;
  esac
done

N=(neon --project-id "$NEON_PROJECT_ID")

# Create the database through the Neon API (not CREATE DATABASE) so it shows up
# in the console with the default owner role.
if ! "${N[@]}" databases list --branch "$NEON_BRANCH" -o json | grep -q "\"name\": \"$NEON_DATABASE\""; then
  echo "Creating Neon database $NEON_DATABASE on branch $NEON_BRANCH"
  "${N[@]}" databases create --branch "$NEON_BRANCH" --name "$NEON_DATABASE" -o json >/dev/null
fi

DATABASE_URL="$("${N[@]}" connection-string "$NEON_BRANCH" --database-name "$NEON_DATABASE")"
umask 077
printf '# Generated by neon/setup.sh. Do not commit.\nDATABASE_URL="%s"\n' "$DATABASE_URL" > "$DB_DIR/.env.production"

if $URL_ONLY; then
  echo "$DATABASE_URL"
  exit 0
fi

echo "Target: Neon project $NEON_PROJECT_ID, branch $NEON_BRANCH, database $NEON_DATABASE"
DATABASE_URL="$DATABASE_URL" exec "$DB_DIR/scripts/migrate.sh" "${args[@]}"
